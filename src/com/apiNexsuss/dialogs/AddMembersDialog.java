    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String firstname = firstnameget.getText();
        String lastname = lastnameget.getText();
        String phonenumber = phoneget.getText();
        String age = ageget.getText();
        String gender = (String) genderget.getSelectedItem();
        String address = addressget.getText();
        String membershipdate = memdateget.getText();
        int status = statusget.getSelectedIndex();
        
        System.out.println(gender);
        
        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
            Connection c = DriverManager.getConnection("jdbc:mysql://127.0.0.1:3306/api_nexsuss", "root", "Savindu@2008");
            Statement s = c.createStatement();
            
            String fullName = firstname+""+lastname;
            
            String query = "INSERT INTO members (Full_Name, phone_number, Age, Gender, Address, membership_date, status_id) " +
                   "VALUES ('" + fullName + "', '" + phonenumber + "', '" + age + "', '" + gender + "', '" + address + "', '" + membershipdate + "', " + status + ")";
            int rowsAffected = s.executeUpdate(query);

            if (rowsAffected > 0) {
                System.out.println("Member added successfully!");
                logger.log(Level.SEVERE,"[SUCCESS] "+fullName+ "Member is successfully added at" + new java.util.Date());
//              
                JOptionPane.showMessageDialog(null, "Member added successfully!");
            } else {
                System.out.println("Added failed. No rows affected.");
            }

            s.close();
            c.close();

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton1ActionPerformed


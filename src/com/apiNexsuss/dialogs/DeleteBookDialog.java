    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String bookId = bookidget.getText();

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
            Connection c = DriverManager.getConnection("jdbc:mysql://127.0.0.1:3306/api_nexsuss", "root", "Savindu@2008");
            Statement s = c.createStatement();
            String query = "DELETE FROM books WHERE id = " + bookId;
            int rowsAffected = s.executeUpdate(query);
            
            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(null, "Book deleted successfully!");
                logger.log(java.util.logging.Level.SEVERE,"[SUCCESS] "+bookId+ "Book deleted successfully at" + new java.util.Date());

            } else {
                JOptionPane.showMessageDialog(null, "No book found with that ID.");
            }

            s.close();
            c.close();

        } catch (Exception e) {
            e.printStackTrace();
        }
        
        init();
        
    }//GEN-LAST:event_jButton1ActionPerformed

